    /** Removes every row, so no data stays on screen after a logout. */
    public void reset(){
        tableModel.setRowCount(0);
    }

    public void init(){
        reset();
        
        ArrayList<Logs> logs = Actions.listLogs();
        for(int nCtr = 0; nCtr < logs.size(); nCtr++){
            tableModel.addRow(new Object[]{
                logs.get(nCtr).getEvent(), 
                logs.get(nCtr).getUsername(), 
                logs.get(nCtr).getDesc(), 
                SQLite.format(logs.get(nCtr).getTimestamp())});
        }
    }
